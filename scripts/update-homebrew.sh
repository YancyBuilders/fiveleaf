#!/bin/sh
# Create or refresh the tap from this fork's published disk images.
set -eu

version="${1:?usage: scripts/update-homebrew.sh <version>}"
case "$version" in
  *[!0-9.]* | "") echo "expected a version such as 0.12.2" >&2; exit 1 ;;
esac
repo="${FIVELEAF_REPOSITORY:-${GITHUB_REPOSITORY:-}}"
if ! printf '%s\n' "$repo" | grep -Eq '^[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*$'; then
  echo "set FIVELEAF_REPOSITORY or GITHUB_REPOSITORY to the fork's owner/repository" >&2
  exit 1
fi
root="$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT HUP INT TERM

gh release download "v$version" --repo "$repo" --dir "$tmp" \
  --pattern "fiveleaf-$version-arm64.dmg" --pattern "fiveleaf-$version-amd64.dmg"
arm="$(shasum -a 256 "$tmp/fiveleaf-$version-arm64.dmg" | cut -d ' ' -f 1)"
intel="$(shasum -a 256 "$tmp/fiveleaf-$version-amd64.dmg" | cut -d ' ' -f 1)"

# No installable cask is committed until FiveLeaf has published disk images.
template="$root/Casks/fiveleaf.rb"
if [ ! -f "$template" ]; then
  template="$root/scripts/fiveleaf.rb.in"
fi
# Keep unrelated edits when updating a cask generated by an earlier release.
awk -v version="$version" -v arm="$arm" -v intel="$intel" -v repo="$repo" '
  /^  version "[^"]*"$/ { $0 = "  version \"" version "\""; versions++ }
  /^  sha256 arm:   "[^"]*",$/ { $0 = "  sha256 arm:   \"" arm "\","; arms++ }
  /^         intel: "[^"]*"$/ { $0 = "         intel: \"" intel "\""; intels++ }
  /^  url "https:\/\/github.com\// {
    $0 = "  url \"https://github.com/" repo "/releases/download/v#{version}/fiveleaf-#{version}-#{arch}.dmg\""
    urls++
  }
  /^  homepage "https:\/\/github.com\// { $0 = "  homepage \"https://github.com/" repo "\""; homes++ }
  /^  command_wrapper "fiveleaf",/ { sub(/"fiveleaf"/, "\"ff\"") }
  /echo "fiveleaf: FiveLeaf\.app is not found"/ { sub(/echo "fiveleaf:/, "echo \"ff:") }
  { print }
  END {
    if (versions != 1 || arms != 1 || intels != 1 || urls != 1 || homes != 1) {
      print "unexpected cask layout; not updating Casks/fiveleaf.rb" > "/dev/stderr"
      exit 1
    }
  }
' "$template" > "$tmp/fiveleaf.rb"
mkdir -p "$root/Casks"
mv "$tmp/fiveleaf.rb" "$root/Casks/fiveleaf.rb"
